#ifdef JOYSHIM_TEST_MSVC_XINPUT_SDK
#define JOYSHIM_STUB_XINPUT_NOEXCEPT noexcept
#else
#define JOYSHIM_STUB_XINPUT_NOEXCEPT
#endif
// 模拟新版 MinGW-w64 系统 XInput 头文件中的公开 C 声明。
// 这些 API 不带 noexcept，且扩展能力 API 使用系统自己的结构体。
struct XINPUT_CAPABILITIES_EX { XINPUT_CAPABILITIES Capabilities; WORD VendorId; WORD ProductId; WORD VersionNumber; WORD Reserved1; DWORD Reserved2; };
